import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';
import tailwindcss from '@tailwindcss/vite';
import { fileURLToPath, URL } from 'node:url';
import { readFileSync, writeFileSync, unlinkSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { productionLicenses } from './build/production-licenses.ts';
const isolatedOutDir = process.env.UI_BUILD_OUT_DIR?.trim();
const buildRoot = isolatedOutDir ? resolve(isolatedOutDir) : fileURLToPath(new URL('../app/ui', import.meta.url));
const generatedList = isolatedOutDir ? resolve(buildRoot, 'generated-assets.json') : fileURLToPath(new URL('./generated-assets.json', import.meta.url));
export default defineConfig({
  plugins: [react(), tailwindcss(), productionLicenses(), {
    name: 'track-owned-build-assets',
    generateBundle() {
      this.emitFile({type:'asset',fileName:'assets/assistant-ui-LICENSE.txt',source:readFileSync(fileURLToPath(new URL('./vendor/assistant-ui-LICENSE',import.meta.url)),'utf8')});
    },
    writeBundle(_options,bundle) {
      const current = Object.keys(bundle).filter(name=>/^assets\/index-[A-Za-z0-9_-]+\.(js|css)$/.test(name));
      const previous:string[] = existsSync(generatedList) ? JSON.parse(readFileSync(generatedList,'utf8')) : [];
      // Only remove exact files recorded as generated by our prior build.
      for (const name of previous) if (!current.includes(name) && /^assets\/index-[A-Za-z0-9_-]+\.(js|css)$/.test(name)) {
        const path = resolve(buildRoot,name);
        if (path.startsWith(resolve(buildRoot,'assets') + '\\') || path.startsWith(resolve(buildRoot,'assets') + '/')) { if (existsSync(path)) unlinkSync(path); }
      }
      writeFileSync(generatedList,JSON.stringify(current,null,2)+'\n');
    }
  }],
  resolve: { alias: { '@': fileURLToPath(new URL('./src', import.meta.url)) } },
  build: { outDir: buildRoot, emptyOutDir: false, assetsDir: 'assets' },
  server: { proxy: { '/chat': 'http://127.0.0.1:8000', '/sessions': 'http://127.0.0.1:8000', '/proposal': 'http://127.0.0.1:8000', '/health': 'http://127.0.0.1:8000', '/quotes':'http://127.0.0.1:8000', '/data-management':'http://127.0.0.1:8000' } },
});
